import numpy as np
import matplotlib.pyplot as plt

from sklearn.datasets import load_iris
from sklearn.preprocessing import StandardScaler

# =====================================
# 1. LOAD DATASET
# =====================================

iris = load_iris()

X = iris.data
y = iris.target

print("Original data shape:", X.shape)

# 150 samples, 4 features

# =====================================
# 2. STANDARDIZE DATA
# =====================================

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

# =====================================
# 3. APPLY SVD
# =====================================

U, S, Vt = np.linalg.svd(
    X_scaled,
    full_matrices=False
)

# =====================================
# 4. SELECT FIRST TWO COMPONENTS
# =====================================

components = Vt[:2, :]

# Project original data into 2 dimensions
X_pca = X_scaled @ components.T

print("Reduced data shape:", X_pca.shape)

# =====================================
# 5. CALCULATE EXPLAINED VARIANCE
# =====================================

explained_variance = S**2 / (len(X) - 1)

variance_ratio = (
    explained_variance /
    np.sum(explained_variance)
)

print("\nExplained variance ratio:")

for i, ratio in enumerate(variance_ratio):
    print(f"PC{i+1}: {ratio * 100:.2f}%")

print(
    "\nTotal variance preserved:",
    f"{np.sum(variance_ratio[:2]) * 100:.2f}%"
)

# =====================================
# 6. VISUALIZE PCA
# =====================================

plt.figure(figsize=(9, 6))

for class_id, name in enumerate(iris.target_names):

    plt.scatter(
        X_pca[y == class_id, 0],
        X_pca[y == class_id, 1],
        label=name,
        s=50
    )

plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")

plt.title("PCA Visualization Using SVD")

plt.legend()
plt.grid(True)
plt.show()

# =====================================
# 7. VISUALIZE EXPLAINED VARIANCE
# =====================================

plt.figure(figsize=(8, 5))

plt.bar(
    ["PC1", "PC2", "PC3", "PC4"],
    variance_ratio * 100
)

plt.ylabel("Explained Variance (%)")
plt.title("Variance Explained by Each Component")

plt.grid(axis="y")
plt.show()

import numpy as np
import matplotlib.pyplot as plt

from sklearn.datasets import load_iris
from sklearn.preprocessing import StandardScaler

# =========================================
# 1. LOAD DATASET
# =========================================

iris = load_iris()

X = iris.data
y = iris.target

print("Original dataset shape:", X.shape)

# 150 samples, 4 features

# =========================================
# 2. STANDARDIZE DATA
# =========================================

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

# =========================================
# 3. BEFORE PCA
# =========================================

# Visualize the first two original features
X_before = X_scaled[:, :2]

# =========================================
# 4. APPLY PCA USING SVD
# =========================================

U, S, Vt = np.linalg.svd(
    X_scaled,
    full_matrices=False
)

# Select first two principal components
components = Vt[:2, :]

# Project data into two dimensions
X_after = X_scaled @ components.T

print("After PCA shape:", X_after.shape)

# =========================================
# 5. VISUALIZE BEFORE AND AFTER PCA
# =========================================

fig, axes = plt.subplots(1, 2, figsize=(14, 6))

colors = ["red", "green", "blue"]

for class_id, name in enumerate(iris.target_names):

    mask = y == class_id

    # BEFORE PCA
    axes[0].scatter(
        X_before[mask, 0],
        X_before[mask, 1],
        label=name,
        color=colors[class_id],
        s=45
    )

    # AFTER PCA
    axes[1].scatter(
        X_after[mask, 0],
        X_after[mask, 1],
        label=name,
        color=colors[class_id],
        s=45
    )

# Before PCA labels
axes[0].set_title("Before PCA (Original Features)")
axes[0].set_xlabel("Sepal Length")
axes[0].set_ylabel("Sepal Width")
axes[0].legend()
axes[0].grid(True)

# After PCA labels
axes[1].set_title("After PCA (Reduced Features)")
axes[1].set_xlabel("Principal Component 1")
axes[1].set_ylabel("Principal Component 2")
axes[1].legend()
axes[1].grid(True)

plt.tight_layout()
plt.show()

# =========================================
# 6. EXPLAINED VARIANCE
# =========================================

variance = S**2 / (len(X) - 1)

variance_ratio = variance / np.sum(variance)

print("\nExplained Variance:")

print(
    "PC1:",
    round(variance_ratio[0] * 100, 2), "%"
)

print(
    "PC2:",
    round(variance_ratio[1] * 100, 2), "%"
)

print(
    "Total variance preserved:",
    round(np.sum(variance_ratio[:2]) * 100, 2), "%"
)