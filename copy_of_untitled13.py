# 1. Load the image as an RGB array
image = Image.open("image.jpg").convert("RGB")
A = np.asarray(image, dtype=np.float64) / 255.0

height, width, channels = A.shape
print("Image shape:", A.shape)

# 2. Perform SVD separately on each color channel
U_list = []
S_list = []
Vt_list = []

for channel in range(channels):
    U, S, Vt = np.linalg.svd(
        A[:, :, channel],
        full_matrices=False
    )

    U_list.append(U)
    S_list.append(S)
    Vt_list.append(Vt)

# 3. Calculate relative reconstruction error for every k
max_k = min(height, width)
total_energy = sum(np.sum(S**2) for S in S_list)

errors = []

for k in range(1, max_k + 1):
    kept_energy = sum(
        np.sum(S[:k] ** 2) for S in S_list
    )

    error = np.sqrt(
        max(total_energy - kept_energy, 0) / total_energy
    )

    errors.append(error)

# 4. Reconstruct the image using a selected k
k = min(50, max_k)

reconstructed = np.zeros_like(A)

for channel in range(channels):
    U = U_list[channel]
    S = S_list[channel]
    Vt = Vt_list[channel]

    reconstructed[:, :, channel] = (
        U[:, :k] * S[:k]
    ) @ Vt[:k, :]

reconstructed = np.clip(reconstructed, 0, 1)

# 5. Display original and compressed images
plt.figure(figsize=(10, 5))

plt.subplot(1, 2, 1)
plt.imshow(A)
plt.title("Original Image")
plt.axis("off")

plt.subplot(1, 2, 2)
plt.imshow(reconstructed)
plt.title(f"Truncated SVD (k={k})")
plt.axis("off")

plt.tight_layout()
plt.show()

# 6. Plot reconstruction error versus k
plt.figure(figsize=(8, 5))
plt.plot(range(1, max_k + 1), errors)
plt.xlabel("Number of singular values (k)")
plt.ylabel("Relative reconstruction error")
plt.title("SVD Image Compression: Error versus k")
plt.grid(True)
plt.show()

print("Relative error:", errors[k - 1])

